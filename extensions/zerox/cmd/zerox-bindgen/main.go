package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"go/types"
	"os"
	"path/filepath"

	"golang.org/x/tools/go/packages"
)

const abiSymbol = "zerox_go_add"

type binding struct {
	SchemaVersion int      `json:"schemaVersion"`
	Package       string   `json:"package"`
	Module        string   `json:"module"`
	ModuleVersion string   `json:"moduleVersion"`
	GoSymbol      string   `json:"goSymbol"`
	ABISymbol     string   `json:"abiSymbol"`
	Target        string   `json:"target"`
	Parameters    []string `json:"parameters"`
	Result        string   `json:"result"`
	ABIType       string   `json:"abiType"`
	Effects       string   `json:"effects"`
}

func main() {
	pkg := flag.String("package", "", "Go package path or relative package directory")
	symbol := flag.String("symbol", "Add", "exported Go function name")
	out := flag.String("out", "", "new directory for the binding artifacts")
	flag.Parse()
	if *pkg == "" || *out == "" || flag.NArg() != 0 {
		flag.Usage()
		os.Exit(2)
	}
	if err := generate(*pkg, *symbol, *out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(pattern, name, out string) error {
	cfg := &packages.Config{
		Mode:       packages.NeedName | packages.NeedTypes | packages.NeedModule,
		BuildFlags: []string{"-mod=readonly", "-buildvcs=false"},
		Env:        append(os.Environ(), "GOOS=linux", "GOARCH=amd64", "CGO_ENABLED=1"),
	}
	matches, err := packages.Load(cfg, pattern)
	if err != nil {
		return err
	}
	if len(matches) != 1 {
		return fmt.Errorf("%q must resolve to exactly one Go package", pattern)
	}
	pkg := matches[0]
	if len(pkg.Errors) != 0 {
		return fmt.Errorf("load %q: %s", pattern, pkg.Errors[0])
	}
	if pkg.Types == nil || pkg.Name == "main" || pkg.Module == nil || pkg.Module.Replace != nil ||
		(!pkg.Module.Main && pkg.Module.Version == "") {
		return fmt.Errorf("%q must resolve to an importable package in the current module or a versioned dependency without a replacement", pattern)
	}
	fn, ok := pkg.Types.Scope().Lookup(name).(*types.Func)
	if !ok || !fn.Exported() {
		return fmt.Errorf("%s.%s must be an exported Go function", pkg.PkgPath, name)
	}
	sig := fn.Signature()
	int64Type := types.Typ[types.Int64]
	if sig.TypeParams().Len() != 0 || sig.Variadic() ||
		sig.Params().Len() != 2 || sig.Results().Len() != 1 ||
		!types.Identical(sig.Params().At(0).Type(), int64Type) ||
		!types.Identical(sig.Params().At(1).Type(), int64Type) ||
		!types.Identical(sig.Results().At(0).Type(), int64Type) {
		return fmt.Errorf("%s.%s: unsupported signature %s; want func(int64, int64) int64", pkg.PkgPath, name, sig)
	}

	version := pkg.Module.Version
	if pkg.Module.Main {
		version = "local"
	}
	meta := binding{
		SchemaVersion: 1, Package: pkg.PkgPath, Module: pkg.Module.Path, ModuleVersion: version,
		GoSymbol: name, ABISymbol: abiSymbol, Target: "linux-x64",
		Parameters: []string{"int64", "int64"}, Result: "int64", ABIType: "int64_t", Effects: "foreign",
	}
	return writeBinding(out, meta)
}

func writeBinding(out string, meta binding) error {
	wrapper, err := format.Source([]byte(fmt.Sprintf(`// Code generated by zerox-bindgen. DO NOT EDIT.
package main

// #include "zerox_go.h"
import "C"

import target %q

var _ func(int64, int64) int64 = target.%s

//export %s
func %s(left, right C.int64_t) C.int64_t {
	return C.int64_t(target.%s(int64(left), int64(right)))
}

func main() {}
`, meta.Package, meta.GoSymbol, meta.ABISymbol, meta.ABISymbol, meta.GoSymbol)))
	if err != nil {
		return err
	}
	header := fmt.Sprintf(`/* Code generated by zerox-bindgen. DO NOT EDIT. */
#ifndef ZEROX_GO_H
#define ZEROX_GO_H

#include <stdint.h>

int64_t %s(int64_t left, int64_t right);

#endif
`, meta.ABISymbol)
	data, err := json.MarshalIndent(meta, "", "  ")
	if err != nil {
		return err
	}
	if err := os.Mkdir(out, 0o755); err != nil {
		return err
	}
	for _, file := range []struct {
		name string
		data []byte
	}{
		{"binding.json", append(data, '\n')},
		{"bridge.go", wrapper},
		{"zerox_go.h", []byte(header)},
	} {
		if err := os.WriteFile(filepath.Join(out, file.name), file.data, 0o644); err != nil {
			return errors.Join(err, os.RemoveAll(out))
		}
	}
	return nil
}
